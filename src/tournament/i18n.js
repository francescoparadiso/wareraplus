export function trnT(key, vars) {
  const lang = getLang();
  const dict = T_DICT[lang] || T_DICT.en;
  let s = dict[key] ?? T_DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
