export function tlT(key, vars) {
  const dict = TL_DICT[getLang()] || TL_DICT.en;
  let s = dict[key] ?? TL_DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
