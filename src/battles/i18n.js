export function btlT(key, vars) {
  const lang = getLang();
  const dict = B_DICT[lang] || B_DICT.en;
  let s = dict[key] ?? B_DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
