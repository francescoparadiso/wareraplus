export function ecoT(key, vars) {
  const d = DICT[getLang()] || DICT.en;
  let s = d[key] ?? DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
