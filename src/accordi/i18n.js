export function acT(key, vars) {
  const lang = getLang();
  let s = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function acErr(code) {
  if (!code) return '';
  const k = `err_${code}`;
  return (DICT[getLang()]?.[k] ?? DICT.en[k]) || acT('err_errore_server');
}
