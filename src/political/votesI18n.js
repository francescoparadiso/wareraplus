export function vT(key, vars) {
  const lang = getLang() || 'en';
  let s = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

/** Il messaggio di un codice d'errore del server, nella lingua di chi guarda. */
export function vErr(codice) {
  const lang = getLang() || 'en';
  return DICT[lang]?.err?.[codice] ?? DICT.en.err[codice] ?? DICT[lang]?.err?.default ?? DICT.en.err.default;
}
