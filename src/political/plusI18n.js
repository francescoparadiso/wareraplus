export function pT(key, vars) {
  const lang = getLang() || 'en';
  let s = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

/** Testi statici delle aggiunte nel markup di Political (`data-wp-pt`). */
export function applyPlusTranslations() {
  const root = document.getElementById('wp-political-root');
  if (!root) return;
  root.querySelectorAll('[data-wp-pt]').forEach(el => { el.textContent = pT(el.getAttribute('data-wp-pt')); });
}
