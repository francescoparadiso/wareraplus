let _i18nLang = (() => {
  try {
    const saved = localStorage.getItem('we_lang');
    if (saved && I18N[saved]) return saved;
  } catch (_) {}
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return I18N[nav] ? nav : 'en';
})();

export function t(key, vars) {
  const dict = I18N[_i18nLang] || I18N.en;
  let str = dict[key] ?? I18N.en[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach(k => {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return str;
}

export function getLang() { return _i18nLang; }

function _applyDirection(lang) {
  document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
}

export function setLang(lang) {
  if (!I18N[lang]) return;
  _i18nLang = lang;
  try { localStorage.setItem('we_lang', lang); } catch (_) {}
  _applyDirection(lang);
  applyStaticTranslations();
  // WarEra+: sincronizza anche il valore visibile del <select> — prima
  // veniva impostato solo una volta in initLangSelector() al mount, quindi
  // chiamare setLang() da fuori (es. src/app/langSync.js, quando lo shell
  // cambia lingua mentre Political è già aperta) traduceva correttamente i
  // testi ma lasciava il menu a tendina fermo sulla lingua precedente.
  const sel = document.getElementById('langSelect');
  if (sel && sel.value !== lang) sel.value = lang;
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

// BUG FIX: prima di questa correzione, le 4 querySelectorAll qui sotto
// giravano su `document` intero invece che sul solo sottoalbero di
// Political. Siccome src/shared/i18n.js (lo shell — menu hamburger ecc.)
// usa DELIBERATAMENTE la stessa convenzione `data-i18n*` (vedi il commento
// in testa a quel file), la prima volta che Political viene montata
// (initI18n() -> applyStaticTranslations(), chiamata da initPoliticalView）
// questo giro spazzava via ANCHE gli elementi data-i18n dello shell (es. il
// pannello del menu hamburger in index.html) — il dizionario I18N qui sopra
// non ha quelle chiavi (es. "app_subtitle", "map_settings"), quindi
// t(key) ricadeva sul fallback `?? key` (riga sopra in t()) scrivendo la
// CHIAVE GREZZA al posto del testo tradotto, in modo permanente (mutazione
// diretta del DOM, non reattiva). Scoping a #wp-political-root: Political
// non ha alcun bisogno di toccare elementi fuori dal proprio root montato.
function _politicalRoot() {
  return document.getElementById('wp-political-root') || document;
}

export function applyStaticTranslations() {
  const root = _politicalRoot();
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
}

export function initLangSelector() {
  const sel = document.getElementById('langSelect');
  if (!sel) return;
  sel.innerHTML = Object.keys(LANGS).map(code => `<option value="${code}">${LANGS[code]}</option>`).join('');
  sel.value = _i18nLang;
  sel.addEventListener('change', () => setLang(sel.value));
}

/**
 * WarEra+ — nell'originale questo bootstrap girava su DOMContentLoaded del
 * documento iframe. Nel path in-page (Stage 5+) il markup Political viene
 * montato lazy DOPO il DOMContentLoaded della pagina shell, quindi questa
 * inizializzazione va richiamata esplicitamente da chi monta il template
 * (src/political/main.js, Stage 8) invece di essere implicita qui.
 * Esportata come funzione a sé; l'export ridondante su `window` (presente
 * nell'originale solo perché le function declaration erano già globali per
 * hoisting) non serve più con import/export espliciti.
 */
export function initI18n() {
  _applyDirection(_i18nLang);
  initLangSelector();
  applyStaticTranslations();
}