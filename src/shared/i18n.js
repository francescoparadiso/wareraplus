const SUPPORTED = Object.keys(DICT); // ['en','it','es','de','fr','nl','sv','pt','ar']
let _lang = _detectInitialLang();

function _detectInitialLang() {
  try {
    // Stessa chiave usata da Political (public/political/i18n.js):
    // localStorage è condiviso (stessa origin), così le due parti
    // dell'app restano sincronizzate sulla lingua senza bisogno di
    // messaggistica esplicita — lo stesso principio già usato per il
    // tema (vedi src/app/themeSync.js).
    const saved = localStorage.getItem('we_lang');
    if (saved && SUPPORTED.includes(saved)) return saved;
  } catch (_) {}
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return SUPPORTED.includes(nav) ? nav : 'en';
}

export function t(key, vars) {
  let str = DICT[_lang]?.[key] ?? DICT.en[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach(k => { str = str.replace(`{${k}}`, vars[k]); });
  }
  return str;
}

export function getLang() {
  return _lang;
}

export function getSupportedLangs() {
  return SUPPORTED;
}

export function setLang(lang) {
  if (!SUPPORTED.includes(lang) || lang === _lang) return;
  _lang = lang;
  try { localStorage.setItem('we_lang', lang); } catch (_) {}
  applyTranslations();
  window.dispatchEvent(new CustomEvent('wareraplus:langchange', { detail: { lang } }));
  // La guardia sopra (lang === _lang) rende questo il punto giusto per il
  // tracking: filtra da sola le chiamate a caricamento/init con la lingua
  // già corrente, restano solo i cambi lingua VERI dell'utente.
  trackEvent('language-change', { lang });
}

// BUG FIX (simmetrico a src/political/i18n.js:applyStaticTranslations):
// `root.querySelectorAll` con root = document intero avrebbe colpito ANCHE
// gli elementi data-i18n* dentro #wp-political-root una volta montata
// (stessa convenzione data-i18n, namespace dizionario diverso — vedi nota
// in testa al file) — es. cambiando lingua dal selettore dello shell mentre
// Political è già aperta, il testo di Political sarebbe stato sovrascritto
// con le chiavi grezze dello shell (fallback di t() su chiave mancante).
// #wp-political-root si autogestisce (src/political/i18n.js), quindi va
// sempre escluso da qui, non solo quando root === document esplicito.
function _skipPoliticalRoot(el) {
  return !!el.closest?.('#wp-political-root');
}

/** Applica le traduzioni a tutti gli elementi con data-i18n* nel documento (shell). */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => {
    if (_skipPoliticalRoot(el)) return;
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    if (_skipPoliticalRoot(el)) return;
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    if (_skipPoliticalRoot(el)) return;
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => {
    if (_skipPoliticalRoot(el)) return;
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
}

/** Popola e aggancia il selettore lingua (<select>) nella top bar. */
export function initLangButton() {
  const select = document.getElementById('wp-lang-select');
  if (!select) return;
  select.innerHTML = SUPPORTED.map(code => `<option value="${code}">${LANGS[code]}</option>`).join('');
  select.value = _lang;
  select.title = t('change_language');
  select.addEventListener('change', () => setLang(select.value));
}
