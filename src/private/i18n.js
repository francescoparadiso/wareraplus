export function pvT(key) {
  return DICT[getLang()]?.[key] ?? DICT.en[key] ?? key;
}

/** Messaggio per un codice d'errore che arriva dal server (`stato_scaduto`
 *  → chiave `errStato_scaduto`). Sconosciuto = errore generico, mai il
 *  codice grezzo in faccia all'utente. */
export function pvErr(code) {
  if (!code) return null;
  const key = `err${code.charAt(0).toUpperCase()}${code.slice(1)}`;
  const msg = DICT[getLang()]?.[key] ?? DICT.en[key];
  return msg || pvT('errErrore_server');
}
