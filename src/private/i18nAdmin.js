/** Etichetta tradotta; `{x}` e `{n}` si sostituiscono con i valori passati. */
export function pmT(key, valori = {}) {
  const t = DICT[getLang()]?.[key] ?? DICT.en[key] ?? key;
  return t.replace(/\{(\w+)\}/g, (_, k) => (valori[k] != null ? String(valori[k]) : ''));
}
